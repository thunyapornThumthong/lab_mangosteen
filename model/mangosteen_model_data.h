// For a pipeline that provides raw 8-bit RGB pixels to this model.
// Apply only AFTER matching the training crop, resize, and channel order.
// This conversion is not for JPEG bytes and does not crop or resize images.
// With this model's scale=1 and zero_point=-128: q = pixel - 128.
// Do not divide by 255 a second time if keeping the source notebook pipeline.
inline int8_t QuantizePixel(uint8_t pixel) {
  return static_cast<int8_t>(static_cast<int>(pixel) - 128);
}

// Dequantize the output score. This is not a calibrated confidence guarantee.
inline float DequantizeScore(int8_t score) {
  return (static_cast<int>(score) - kOutputZeroPoint) * kOutputScale;
}

